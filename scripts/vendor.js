// Copies the few third-party browser assets the desktop and mobile UIs need
// into src/*/vendor so that both UIs load everything locally (no CDN, works offline).
// Runs automatically after `npm install` (postinstall) and before every build.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const lucideDir = path.join(root, 'node_modules/lucide/dist/esm/icons');

// Every icon used anywhere in the UI. Unknown names fail loudly here instead of
// rendering an empty square at runtime.
const ICONS = [
  'layout-dashboard', 'wifi', 'usb', 'folder-up', 'folder-down', 'clock', 'settings', 'info',
  'play', 'square', 'qr-code', 'copy', 'refresh-cw', 'trash', 'search', 'x', 'check',
  'circle-exclamation-point', 'triangle-exclamation-point', 'monitor', 'smartphone', 'sun', 'moon',
  'external-link', 'pencil', 'plus', 'folder-plus', 'file-plus', 'file', 'file-text', 'file-image',
  'file-play', 'file-music', 'file-archive', 'file-spreadsheet', 'image', 'images', 'files', 'download',
  'upload', 'folder-open', 'shield', 'cable', 'server', 'activity', 'hard-drive', 'loader-circle', 'eye',
  'arrow-up-down', 'link', 'circle-check', 'circle-x', 'hourglass', 'network', 'lock', 'unplug',
  'plug-zap', 'circle-question-mark', 'mail', 'globe', 'pause', 'rotate-ccw', 'log-out', 'bell',
  'chevron-right', 'list-checks', 'arrow-down', 'arrow-up', 'presentation', 'wifi-off',
];

async function buildIcons() {
  const out = {};
  for (const name of ICONS) {
    const file = path.join(lucideDir, `${name}.mjs`);
    if (!fs.existsSync(file)) throw new Error(`lucide icon not found: ${name}`);
    const mod = await import(pathToFileURL(file).href);
    out[name] = mod.default.map(([tag, attrs]) => {
      const a = Object.entries(attrs).map(([k, v]) => `${k}="${String(v).replace(/"/g, '&quot;')}"`).join(' ');
      return `<${tag} ${a}/>`;
    }).join('');
  }
  return `/* Generated by scripts/vendor.js from lucide (ISC license). Do not edit. */
const PATHS = ${JSON.stringify(out)};
export function icon(name, size = 18, cls = '') {
  const body = PATHS[name] || PATHS['file'];
  return '<svg class="icon ' + cls + '" xmlns="http://www.w3.org/2000/svg" width="' + size + '" height="' + size +
    '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' +
    body + '</svg>';
}
export function hydrateIcons(rootEl = document) {
  for (const el of rootEl.querySelectorAll('[data-icon]')) {
    el.innerHTML = icon(el.dataset.icon, Number(el.dataset.size) || 18);
    el.removeAttribute('data-icon');
  }
}
`;
}

const iconsJs = await buildIcons();
for (const ui of ['desktop', 'mobile']) {
  const dir = path.join(root, 'src', ui, 'vendor');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'icons.js'), iconsJs);
}
// The phone verifies upload chunks with the same CRC-32 code as the server.
fs.copyFileSync(path.join(root, 'src/shared/crc32.js'), path.join(root, 'src/mobile/vendor/crc32.js'));
console.log(`[vendor] wrote ${ICONS.length} icons to src/desktop/vendor and src/mobile/vendor`);
