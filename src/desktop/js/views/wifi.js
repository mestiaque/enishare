import { state, api } from '../store.js';
import { icon, esc, toast, toastError, modal, checkRow, busy } from '../ui.js';
import { toggleSharing, WARNINGS } from './common.js';

let root; let ctx; let qrFor = null; let countdown = null;

async function loadQr() {
  const box = root?.querySelector('#qr');
  if (!box) return;
  if (!state.server?.running) {
    box.className = 'qr-box off';
    box.innerHTML = `<div>${icon('qr-code', 48)}<div class="mt-s">Start sharing to show the QR code</div></div>`;
    qrFor = null;
    return;
  }
  try {
    const { svg, pairUrl } = await api.call('server.qr');
    if (!root) return;
    qrFor = pairUrl;
    box.className = 'qr-box';
    // The SVG is generated by the qrcode library in our own server process.
    box.innerHTML = svg || `<div class="faint">No network address</div>`;
  } catch (err) { toastError(err, 'Could not create the QR code'); }
}

function tickCountdown() {
  const el = root?.querySelector('#qr-expiry');
  if (!el || !state.server?.running) return;
  const left = Math.max(0, Math.round((state.server.pairExpiresAt - Date.now()) / 1000));
  el.textContent = `QR code changes in ${Math.floor(left / 60)}:${String(left % 60).padStart(2, '0')} · each code works once`;
}

function interfaceOptions() {
  const ifaces = state.network?.interfaces ?? [];
  const sel = state.settings?.interfaceName ?? '';
  const auto = `<option value="" ${sel ? '' : 'selected'}>Automatic (recommended)</option>`;
  return auto + ifaces.map((i) => `<option value="${esc(i.name)}" ${sel === i.name ? 'selected' : ''}>${esc(i.label)} — ${esc(i.name)} — ${esc(i.address)}</option>`).join('');
}

function render() {
  const s = state.server ?? {};
  const warning = state.network?.selection?.warning;
  const online = state.stats?.devicesOnline ?? 0;
  const iface = state.network?.interfaces?.find((i) => i.name === state.network?.selection?.iface);
  root.innerHTML = `
    ${warning && WARNINGS[warning] ? `<div class="alert warn">${icon('triangle-exclamation-point', 18)}<div>${esc(WARNINGS[warning])}</div></div>` : ''}
    ${iface && iface.kind === 'iphone-usb' ? `<div class="alert info">${icon('cable', 18)}<div><b>Using the iPhone USB hotspot network</b>Data travels over the cable. See USB / Cable for details.</div></div>` : ''}
    <div class="card">
      <div class="qr-wrap">
        <div class="col" style="align-items:center">
          <div id="qr" class="qr-box off"></div>
          <div class="tiny faint" id="qr-expiry"></div>
        </div>
        <div class="grow col" style="gap:14px">
          <div class="row">
            <span class="badge ${s.running ? 'ok' : ''}">${s.running ? '<span class="dot on"></span>Sharing' : 'Not sharing'}</span>
            <span class="badge ${online ? 'ok' : ''}" id="online-badge">${icon('smartphone', 12)} ${online} connected</span>
            ${iface ? `<span class="badge info">${icon(iface.kind === 'wifi' ? 'wifi' : iface.kind === 'iphone-usb' ? 'cable' : 'network', 12)} ${esc(iface.label)}</span>` : ''}
          </div>
          <div>
            <div class="small muted" style="margin-bottom:6px">Address for the iPhone</div>
            <div class="url-box"><span class="grow selectable ellipsis">${esc(s.url || 'No network address')}</span>
              <button class="btn sm" id="copy" ${s.url ? '' : 'disabled'}>${icon('copy', 14)} Copy</button></div>
            <div class="tiny faint mt-s">Typing this address shows the PIN screen${state.settings?.pinEnabled ? '' : ' — enable PIN pairing in Settings to use it'}. The QR code pairs instantly.</div>
          </div>
          <div class="row wrap">
            <button class="btn ${s.running ? 'danger' : 'primary'}" id="toggle">${icon(s.running ? 'square' : 'play', 16)} ${s.running ? 'Stop Sharing' : 'Start Sharing'}</button>
            <button class="btn" id="refresh" ${s.running ? '' : 'disabled'}>${icon('refresh-cw', 16)} Refresh QR</button>
            <button class="btn ghost" id="diag">${icon('circle-question-mark', 16)} iPhone can't connect?</button>
          </div>
          <div>
            <div class="section-label" style="margin-top:4px">How to connect</div>
            <ol class="steps">
              <li>Connect the iPhone to the <b>same Wi-Fi</b> as this PC.</li>
              <li>Open the iPhone <b>Camera</b> and point it at the QR code.</li>
              <li>Tap the <b>link</b> that appears — ENiShare opens in Safari.</li>
              <li>Upload photos and documents, or download files shared from this PC.</li>
            </ol>
          </div>
        </div>
      </div>
    </div>
    <div class="card">
      <h2>${icon('network', 16)} Network interface</h2>
      <div class="setting"><div><div>Interface used for the QR code</div><div class="hint">ENiShare skips virtual adapters (Docker, VirtualBox, Hyper-V…) and VPNs unless you pick one here.</div></div>
        <select class="input" id="iface">${interfaceOptions()}</select></div>
      <div class="setting"><div><div>Manual IP address</div><div class="hint">Only needed if automatic detection picks the wrong address.</div></div>
        <div class="row"><input class="input" id="manual" placeholder="e.g. 192.168.1.20" value="${esc(state.settings?.autoDetectIp ? '' : state.settings?.manualIp || '')}"><button class="btn" id="manual-save">Use</button></div></div>
      <div class="row end mt-s"><button class="btn ghost sm" id="rescan">${icon('refresh-cw', 14)} Rescan network</button></div>
    </div>`;

  root.querySelector('#toggle').onclick = (e) => toggleSharing(e.currentTarget);
  root.querySelector('#copy').onclick = async () => { await api.copyText(s.url); toast({ kind: 'success', title: 'Address copied', timeout: 1500 }); };
  const refresh = root.querySelector('#refresh');
  refresh.onclick = busy(refresh, async () => { await api.call('pairing.refresh'); toast({ kind: 'info', title: 'New QR code created', timeout: 1500 }); });
  root.querySelector('#diag').onclick = showDiagnostics;
  root.querySelector('#iface').onchange = async (e) => {
    try { await api.call('settings.update', { patch: { interfaceName: e.target.value, autoDetectIp: true, manualIp: '' } }); } catch (err) { toastError(err); }
  };
  const manualSave = root.querySelector('#manual-save');
  manualSave.onclick = busy(manualSave, async () => {
    const v = root.querySelector('#manual').value.trim();
    await api.call('settings.update', { patch: v ? { manualIp: v, autoDetectIp: false } : { manualIp: '', autoDetectIp: true } });
    toast({ kind: 'success', title: v ? `Using ${v}` : 'Automatic detection restored', timeout: 2000 });
  });
  const rescan = root.querySelector('#rescan');
  rescan.onclick = busy(rescan, async () => { state.network = await api.call('network.refresh'); render(); });
  loadQr();
  tickCountdown();
}

async function showDiagnostics() {
  const body = document.createElement('div');
  body.innerHTML = `<div class="empty">${icon('loader-circle', 24, 'spin')}<div>Checking…</div></div>`;
  modal({ title: 'Connection check', body, wide: true, actions: [{ label: 'Close', kind: 'primary', value: true }] });
  try {
    const d = await api.call('network.diagnostics');
    body.innerHTML = `<div class="checks">${d.checks.map(checkRow).join('')}</div>
      <div class="section-label">If the iPhone still cannot connect</div>
      <ul class="steps">${d.tips.map((t) => `<li>${esc(t)}</li>`).join('')}</ul>`;
  } catch (err) { body.innerHTML = `<div class="alert err">${esc(err.message)}</div>`; }
}

export default {
  subtitle: 'Connect your iPhone over the local network',
  mount(el, c) {
    root = el; ctx = c; render();
    countdown = setInterval(tickCountdown, 1000);
  },
  update(what) {
    if (!root) return;
    if (what === 'server') {
      // Re-render controls; reload the QR when the pairing URL changed.
      render();
      return;
    }
    if (what === 'stats' || what === 'devices') {
      const b = root.querySelector('#online-badge');
      const online = state.stats?.devicesOnline ?? 0;
      if (b) { b.className = `badge ${online ? 'ok' : ''}`; b.innerHTML = `${icon('smartphone', 12)} ${online} connected`; }
      return;
    }
    if (['network', 'settings', 'all'].includes(what)) render();
  },
  unmount() { clearInterval(countdown); root = null; qrFor = null; },
};
